"""Pre-generate Mandarin audio clips for index.html with Kokoro v1.1-zh (sherpa-onnx).

Usage:
    uv run scripts/generate_audio.py --model-dir path/to/kokoro-multi-lang-v1_1

Model download (about 420 MB, not committed):
    https://github.com/k2-fsa/sherpa-onnx/releases/download/tts-models/kokoro-multi-lang-v1_1.tar.bz2

Writes audio/kokoro/<hash>-n.mp3 (normal) and <hash>-s.mp3 (slow) plus audio/manifest.js,
which the page loads to map spoken text -> clip.
"""
import argparse
import hashlib
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
HTML_PATH = ROOT / "index.html"
AUDIO_DIR = ROOT / "audio"
CLIP_DIR = AUDIO_DIR / "kokoro"
MANIFEST_PATH = AUDIO_DIR / "manifest.js"

# Kokoro v1.1-zh speaker ids (0-2 are English voices, Chinese voices follow by number).
VOICES = {"zf_001": 3, "zf_002": 4, "zf_004": 6, "zm_010": 12}
SPEEDS = {"n": 1.0, "s": 0.6}
MP3_KBPS = 64

# Every field whose value index.html passes to speakText().
SPOKEN_FIELD_RE = re.compile(r"\b(?:rawText|hanzi|example|titleZh|fullZh):\s*'([^']+)'")
TOKEN_RE = re.compile(r"\{\s*char:\s*'([^']+)'[^}]*\}")


def extract_spoken_texts(html: str) -> list[str]:
    """Return every distinct string the page can speak, in first-seen order."""
    texts = SPOKEN_FIELD_RE.findall(html)
    texts += [m.group(1) for m in TOKEN_RE.finditer(html) if "isPunct" not in m.group(0)]
    return list(dict.fromkeys(t.strip() for t in texts if t.strip()))


def clip_id(text: str) -> str:
    return hashlib.sha1(text.encode("utf-8")).hexdigest()[:12]


def build_tts(model_dir: Path):
    import sherpa_onnx

    d = model_dir
    cfg = sherpa_onnx.OfflineTtsConfig(
        model=sherpa_onnx.OfflineTtsModelConfig(
            kokoro=sherpa_onnx.OfflineTtsKokoroModelConfig(
                model=str(d / "model.onnx"),
                voices=str(d / "voices.bin"),
                tokens=str(d / "tokens.txt"),
                data_dir=str(d / "espeak-ng-data"),
                dict_dir=str(d / "dict"),
                lexicon=f"{d / 'lexicon-us-en.txt'},{d / 'lexicon-zh.txt'}",
            ),
            num_threads=4,
        ),
        rule_fsts=f"{d / 'phone-zh.fst'},{d / 'date-zh.fst'},{d / 'number-zh.fst'}",
    )
    if not cfg.validate():
        sys.exit(f"Kokoro model files missing or invalid in {d}")
    return sherpa_onnx.OfflineTts(cfg)


def encode_mp3(samples, sample_rate: int) -> bytes:
    import lameenc
    import numpy as np

    pcm = (np.clip(np.asarray(samples), -1.0, 1.0) * 32767).astype("<i2").tobytes()
    enc = lameenc.Encoder()
    enc.set_bit_rate(MP3_KBPS)
    enc.set_in_sample_rate(sample_rate)
    enc.set_channels(1)
    enc.set_quality(2)
    return enc.encode(pcm) + enc.flush()


def write_manifest(
    voice: str,
    clips: dict[str, str],
    *,
    path: Path = MANIFEST_PATH,
    clip_dir: str = "audio/kokoro",
    speeds: dict[str, float] = SPEEDS,
) -> None:
    data = {"voice": voice, "dir": clip_dir, "speeds": speeds, "clips": clips}
    body = json.dumps(data, ensure_ascii=False, indent=1)
    path.write_text(
        "// Generated by scripts/ (generate_audio.py or tts_xfyun.py). Do not edit by hand.\n"
        f"window.LESSON_AUDIO = {body};\n",
        encoding="utf-8",
    )


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--model-dir", type=Path, required=True)
    parser.add_argument("--voice", choices=sorted(VOICES), default="zf_001")
    parser.add_argument("--force", action="store_true", help="re-render clips that already exist")
    args = parser.parse_args()

    texts = extract_spoken_texts(HTML_PATH.read_text(encoding="utf-8"))
    if not texts:
        sys.exit("No spoken text found in index.html; did the data format change?")

    CLIP_DIR.mkdir(parents=True, exist_ok=True)
    tts = build_tts(args.model_dir)
    sid = VOICES[args.voice]
    clips: dict[str, str] = {}
    failures: list[str] = []

    for i, text in enumerate(texts, 1):
        cid = clip_id(f"{args.voice}|{text}")
        clips[text] = cid
        for suffix, speed in SPEEDS.items():
            out = CLIP_DIR / f"{cid}-{suffix}.mp3"
            if out.exists() and not args.force:
                continue
            audio = tts.generate(text, sid=sid, speed=speed)
            if len(audio.samples) == 0:
                failures.append(f"{text} ({suffix})")
                continue
            out.write_bytes(encode_mp3(audio.samples, audio.sample_rate))
        print(f"[{i}/{len(texts)}] {text}")

    used = {f"{cid}-{s}.mp3" for cid in clips.values() for s in SPEEDS}
    for stale in CLIP_DIR.glob("*.mp3"):
        if stale.name not in used:
            stale.unlink()

    write_manifest(args.voice, clips)
    print(f"Wrote {len(clips)} clips x {len(SPEEDS)} speeds, voice {args.voice}")
    if failures:
        sys.exit("Empty audio for: " + ", ".join(failures))


if __name__ == "__main__":
    main()
